"""Generate the chart of accounts XML from a QuickBooks Account Listing

Export the listing from QuickBooks Desktop with
Lists > Chart of Accounts > Reports > Account Listing, save the Account, Type,
Description and Accnt. # columns as CSV and run:

    generate_chart.py accounts.csv chart_id "Chart Name" > chart.xml
"""
import csv
import sys
from xml.sax.saxutils import escape, quoteattr

# QuickBooks account type to account type template id of account_us.xml
TYPES = {
    'Bank': 'type_asset_current_cash',
    'Accounts Receivable': 'type_asset_current_receivable',
    'Other Current Asset': 'type_asset_current_other',
    'Fixed Asset': 'type_asset_fixed',
    'Other Asset': 'type_asset_other',
    'Accounts Payable': 'type_liability_current_payable',
    'Credit Card': 'type_liability_current_credit_card',
    'Other Current Liability': 'type_liability_current_other',
    'Long Term Liability': 'type_liability_long_term',
    'Equity': 'type_equity',
    'Income': 'type_revenue',
    'Cost of Goods Sold': 'type_cogs',
    'Expense': 'type_expense_operating',
    'Other Income': 'type_revenue_other',
    'Other Expense': 'type_expense_other',
    }
# Accounts holding inventory value are typed as stock for the stock modules
INVENTORY_CODES = {'1120', '1125', '1130', '1135', '1140', '1145', '1150',
    '1155'}
SEPARATOR = ' · '


def split_name(segment):
    "Return code and name of a QuickBooks account segment"
    if SEPARATOR in segment:
        code, name = segment.split(SEPARATOR, 1)
        return code.strip(), name.strip()
    return None, segment.strip()


def xml_id(prefix, path):
    key = []
    for segment in path:
        code, name = split_name(segment)
        if code:
            key.append(code)
        else:
            # Unnumbered accounts may have a name equal to a number
            key.append('n_' + ''.join(c if c.isalnum() else '_'
                    for c in name.lower()).strip('_'))
    return prefix + '_' + '_'.join(key)


def main(filename, chart_id, chart_name):
    with open(filename, newline='', encoding='utf-8') as fp:
        rows = list(csv.DictReader(fp))
    records = []
    ids = set()
    for row in rows:
        type_ = row['Type']
        if type_ == 'Non-Posting':
            continue
        path = row['Account'].split(':')
        code, name = split_name(path[-1])
        record_id = xml_id(chart_id, path)
        if record_id in ids:
            raise ValueError("Duplicate account %s" % row['Account'])
        ids.add(record_id)
        if len(path) > 1:
            parent = xml_id(chart_id, path[:-1])
        else:
            parent = chart_id
        type_id = TYPES[type_]
        if code in INVENTORY_CODES:
            type_id = 'type_asset_current_inventory'
        records.append({
                'id': record_id,
                'code': code,
                'name': name,
                'type': type_id,
                'parent': parent,
                'reconcile': type_ in {'Accounts Receivable',
                    'Accounts Payable'},
                'party_required': type_ in {'Accounts Receivable',
                    'Accounts Payable'},
                })
    out = sys.stdout
    out.write('<?xml version="1.0"?>\n')
    out.write('<!-- This file is part of Tryton.  The COPYRIGHT file at the '
        'top level of\nthis repository contains the full copyright notices '
        'and license terms.\n'
        'Generated by scripts/generate_chart.py -->\n')
    out.write('<tryton>\n    <data>\n')
    out.write('        <record model="account.account.template" id=%s>\n'
        % quoteattr(chart_id))
    out.write('            <field name="name">%s</field>\n'
        % escape(chart_name))
    out.write('            <field name="type" ref="type_root"/>\n')
    out.write('            <field name="closed" eval="True"/>\n')
    out.write('        </record>\n')
    for record in records:
        out.write('\n        <record model="account.account.template" '
            'id=%s>\n' % quoteattr(record['id']))
        out.write('            <field name="name">%s</field>\n'
            % escape(record['name']))
        if record['code']:
            out.write('            <field name="code">%s</field>\n'
                % escape(record['code']))
        out.write('            <field name="type" ref=%s/>\n'
            % quoteattr(record['type']))
        out.write('            <field name="parent" ref=%s/>\n'
            % quoteattr(record['parent']))
        if record['reconcile']:
            out.write('            <field name="reconcile" eval="True"/>\n')
        if record['party_required']:
            out.write(
                '            <field name="party_required" eval="True"/>\n')
        out.write('        </record>\n')
    out.write('    </data>\n</tryton>\n')


if __name__ == '__main__':
    main(*sys.argv[1:4])
