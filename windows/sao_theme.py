"""Recolour the Tryton web client (sao 7.0) for N-Line: every rule of
sao/dist/tryton-sao.css that uses its teal is repeated in custom.css with
N-Line's colours, between the "BEGIN sao colours" / "END sao colours"
markers.

    python windows/sao_theme.py

Run it again after an upgrade of sao.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SAO_CSS = os.path.join(HERE, 'sao', 'dist', 'tryton-sao.css')
CUSTOM = os.path.join(HERE, 'sao', 'custom.css')

# sao's teal -> N-Line navy (actions) and its light blue
COLORS = {
    '#267f82': '#1f4e8c',
    '#1a585b': '#163a69',
    '#185153': '#12305a',
    '#71bdc1': '#6b9bd8',
    '#4aa6aa': '#4a7fc4',
}
BEGIN = '/* BEGIN sao colours (generated by windows/sao_theme.py) */'
END = '/* END sao colours */'


def overrides():
    css = open(SAO_CSS, encoding='utf-8').read()
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    pattern = re.compile('|'.join(COLORS), re.I)
    out = []
    # Plain rules only (the @media blocks of sao do not use the teal)
    for selector, body in re.findall(r'([^{}@]+)\{([^{}]*)\}', css):
        declarations = [d.strip() for d in body.split(';')
            if pattern.search(d)]
        if not declarations:
            continue
        declarations = [pattern.sub(lambda m: COLORS[m.group(0).lower()], d)
            for d in declarations]
        out.append('%s { %s; }' % (' '.join(selector.split()),
                '; '.join(declarations)))
    return out


def main():
    custom = open(CUSTOM, encoding='utf-8').read()
    block = '%s\n%s\n%s' % (BEGIN, '\n'.join(overrides()), END)
    if BEGIN in custom:
        start = custom.index(BEGIN)
        end = custom.index(END) + len(END)
        custom = custom[:start] + block + custom[end:]
    else:
        # Before the N-Line rules, so they win over the generated ones
        marker = '/* The header: a light bar'
        custom = custom.replace(marker, block + '\n\n' + marker, 1)
    open(CUSTOM, 'w', encoding='utf-8', newline='\n').write(custom)
    print('custom.css: %d sao rules recoloured' % len(overrides()))


if __name__ == '__main__':
    main()
